const dictionaries: Record<Locale, Strings> = { en, fr };

export type StringKey = keyof Strings;

export function translate(locale: Locale, key: StringKey, params?: Record<string, string | number>): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
